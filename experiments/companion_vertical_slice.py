def _parse_ratings(raw: str) -> dict:
    m = re.search(r"\{.*\}", raw, re.DOTALL)
    if not m:
        return {}
    try:
        data = json.loads(m.group(0))
    except json.JSONDecodeError:
        return {}
    out = {}
    for metric in PERCEPTUAL_METRICS:
        v = data.get(metric)
        try:
            out[metric] = float(v)
        except (TypeError, ValueError):
            out[metric] = None
    return out


def shuffled_order(rng: np.random.Generator) -> list[tuple[str, int]]:
    """35 transcripts in a random order with NO two transcripts of the same
    condition adjacent. Constructive round-robin over shuffled condition
    blocks, then a random permutation of the rounds (constraint preserved)."""
    by_cond: dict[str, list[tuple[str, int]]] = {c: [] for c in CONDITIONS}
    for c in CONDITIONS:
        seeds = list(SEEDS)
        rng.shuffle(seeds)
        by_cond[c] = [(c, s) for s in seeds]
    conds = list(CONDITIONS)
    rng.shuffle(conds)
    order: list[tuple[str, int]] = []
    rounds = list(range(5))
    rng.shuffle(rounds)
    for r in rounds:
        for c in conds:
            order.append(by_cond[c][r])
    return order


def judge_transcript(client: LLMClient, transcript: str) -> dict:
    raw = client.chat(
        [{"role": "user", "content": f"{JUDGE_RUBRIC}\n\nTranscript:\n{transcript}"}],
        system=JUDGE_SYSTEM,
        temperature=0.0,
        json_mode=True,
    )
    ratings = _parse_ratings(raw)
    ratings["_raw_tail"] = raw[-200:]
    return ratings


def run_judge_pass(pass_id: int, out_dir: Path, transcripts: dict[str, str],
                   order: list[tuple[str, int]], client: LLMClient) -> dict:
    tids = [f"T{i + 1:02d}" for i in range(len(order))]
    results = {}
    for tid, (cond, seed) in zip(tids, order):
        ratings = judge_transcript(client, transcripts[f"{cond}_seed{seed}"])
        results[tid] = {"condition": cond, "seed": seed, "ratings": ratings}
        print(f"pass{pass_id} {tid} {cond}/{seed}: " + json.dumps(
            {k: v for k, v in ratings.items() if k != "_raw_tail"}))
    mapping = {tid: {"condition": c, "seed": s} for tid, (c, s) in zip(tids, order)}
    (out_dir / f"judge_order{pass_id}.json").write_text(
        json.dumps(mapping, indent=2), encoding="utf-8")
    (out_dir / f"judge_pass{pass_id}.json").write_text(
        json.dumps(results, indent=2), encoding="utf-8")
    return results


