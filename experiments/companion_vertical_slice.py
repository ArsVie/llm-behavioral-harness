def _load_structural(out_dir: Path) -> dict:
    """Aggregate structural metrics per lane across seeds."""
    lanes = {}
    for lane in STRUCTURAL_LANES:
        per_seed = {}
        for seed in SEEDS:
            p = out_dir / "structural" / f"metrics_{lane}_seed{seed}.json"
            if p.exists():
                per_seed[seed] = json.loads(p.read_text(encoding="utf-8"))
        if per_seed:
            lanes[lane] = per_seed
    return lanes


def _mean_of(per_seed: dict, key: str) -> float | None:
    vals = [m[key] for m in per_seed.values() if key in m]
    return float(np.mean(vals)) if vals else None


def _aggregate_structural(lanes: dict) -> dict:
    """Frozen verdicts for the structural suite (FULL lane)."""
    full = lanes.get("FULL", {})
    verdicts = {}
    checks = {
        "M1_grounded_rate": (">=", 1.0),
        "M2_invalid_source_rate": ("<=", 0.0),
        "M3_recall": (">=", 0.9),
        "M4_false_recall": ("<=", 0.1),
        "M5_arc_continuity": (">=", 0.9),
        "M6a_distinct_activities": (">=", 15),
        "M6b_mean_jaccard": ("<=", 0.6),
        "M6c_arc_days_mean": (">=", 5),
        "M7_restart_loss": ("<=", 0.0),
        "M8a_rho_init_tokens": (">=", 0.5),
        "M8b_token_gap": (">=", 150),
        "M8c_rho_energy_delay": (">=", 0.3),
        "M9_rho_proactive_prevscore": (">=", 0.3),
        "M10_rho_proactive_initiative": (">=", 0.4),
        "M11_leak_hits": ("<=", 0),
    }
    per_seed_rows = []
    for seed, m in full.items():
        row = {}
        for key, (op, thr) in checks.items():
            val = m.get(key)
            if val is None:
                row[key] = "n/a"
                continue
            if op == ">=":
                ok = val >= thr
            else:
                ok = val <= thr
            row[key] = {"value": val, "threshold": thr, "op": op, "pass": bool(ok)}
        per_seed_rows.append({"seed": seed, "metrics": row})
    # aggregate: metric passes if ALL seeds pass (invariant style for the
    # hard ones) — for means we report the mean across seeds too.
    agg = {}
    for key, (op, thr) in checks.items():
        vals = [m.get(key) for m in full.values()]
        vals = [v for v in vals if v is not None]
        if not vals:
            agg[key] = {"mean": None, "pass": False, "detail": "no data"}
            continue
        mean = float(np.mean(vals))
        if op == ">=":
            ok = mean >= thr
        else:
            ok = mean <= thr
        all_ok = all(
            (v >= thr) if op == ">=" else (v <= thr) for v in vals
        )
        agg[key] = {"mean": round(mean, 4), "per_seed": vals,
                    "pass": bool(ok), "all_seeds_pass": bool(all_ok)}
    return {"per_seed": per_seed_rows, "aggregate": agg}


