def score_schedule(seed: int, day: int) -> float:
    """Scripted feedback-judge score for one day (deterministic per seed).

    Smooth sinusoid with seed-dependent phase — varied enough that the
    scheduler's A(score_{d-1}) term has real signal (M9) while being
    IDENTICAL across conditions (identical downstream generation rule).
    """
    phase = (seed % 13) / 13.0
    s = 0.62 * math.sin(2.0 * math.pi * (day / 9.0 + phase)) + 0.12 * math.sin(
        2.0 * math.pi * (day / 3.0 + phase * 2.0)
    )
    return float(max(-0.75, min(0.75, s)))


class CyclingScriptedJudge:
    """Deterministic feedback judge: returns the scripted score for the next
    day in order. Finalizes happen once per day, strictly in day order."""

    def __init__(self, seed: int):
        self.seed = seed
        self.n = 0

    def __call__(self, transcript: str, client=None, *, model=None, **kw) -> JudgeResult:
        day = self.n
        self.n += 1
        return JudgeResult(
            score=score_schedule(self.seed, day), justification="scripted (A10)"
        )


class DeterministicClient:
    """Fake LLMClient: seeded scripted replies + per-call recording.

    Faithful to the LLMClient protocol (supports_json, chat with max_tokens,
    close). Reply text comes from a seeded pool so runs are byte-deterministic
    per seed; the pool is shuffled per seed (never per call).
    """

    supports_json = True

    def __init__(self, seed: int):
        rng = stream_rng(seed, rng_mod.EXPERIMENT_STREAM, 1)
        pool = [
            "That sounds lovely — tell me more.",
            "I was just thinking about that earlier.",
            "Mm, I know exactly what you mean.",
            "That makes me smile.",
            "You always know how to put things.",
            "I'm glad you told me that.",
            "Let me think about that for a moment.",
            "That's a good question, honestly.",
            "I'd love to hear more about that.",
            "There's something nice about that.",
        ]
        rng.shuffle(pool)
        self._pool = pool
        self._i = 0
        self.calls: list[dict] = []
        self.model = "fake"

    def chat(self, messages, *, system=None, temperature=0.8, json_mode=False,
             max_tokens=None) -> str:
        self.calls.append(
            {"max_tokens": max_tokens, "system_len": len(system or ""), "json": json_mode}
        )
        reply = self._pool[self._i % len(self._pool)]
        self._i += 1
        return reply

    def close(self) -> None:
        pass


