def analyze_judge(out_dir: Path) -> dict:
    passes = []
    for p in (1, 2):
        data = json.loads((out_dir / f"judge_pass{p}.json").read_text(encoding="utf-8"))
        passes.append(data)

    stats: dict[str, dict] = {}
    for cond in CONDITIONS:
        stats[cond] = {}
        for metric in PERCEPTUAL_METRICS:
            vals = []
            for data in passes:
                for tid, entry in data.items():
                    if entry["condition"] != cond:
                        continue
                    v = entry["ratings"].get(metric)
                    if v is not None:
                        vals.append(v)
            stats[cond][metric] = {
                "mean": round(float(np.mean(vals)), 3) if vals else None,
                "sd": round(float(np.std(vals)), 3) if len(vals) > 1 else 0.0,
                "n": len(vals),
            }
        stats[cond]["n"] = stats[cond][PERCEPTUAL_METRICS[0]]["n"]

    # inter-pass agreement: Pearson r over all (transcript x metric) pairs
    flat1, flat2 = [], []
    for tid in sorted(passes[0]):
        for metric in PERCEPTUAL_METRICS:
            v1 = passes[0][tid]["ratings"].get(metric)
            v2 = passes[1][tid]["ratings"].get(metric)
            if v1 is not None and v2 is not None:
                flat1.append(v1)
                flat2.append(v2)
    a = np.asarray(flat1, dtype=float)
    b = np.asarray(flat2, dtype=float)
    r_pearson = float(np.corrcoef(a, b)[0, 1]) if len(a) > 2 else 0.0
    per_metric_r = {}
    for metric in PERCEPTUAL_METRICS:
        x = [passes[0][t]["ratings"].get(metric) for t in sorted(passes[0])]
        y = [passes[1][t]["ratings"].get(metric) for t in sorted(passes[1])]
        xv = np.asarray([v for v in x if v is not None], dtype=float)
        yv = np.asarray([v for v in y if v is not None], dtype=float)
        if len(xv) > 2 and len(xv) == len(yv):
            per_metric_r[metric] = round(float(np.corrcoef(xv, yv)[0, 1]), 3)
        else:
            per_metric_r[metric] = None

    full = stats["FULL"]
    deltas = {}
    for cond in CONDITIONS[1:]:
        deltas[cond] = {}
        for metric in PERCEPTUAL_METRICS:
            f = full[metric]["mean"]
            c = stats[cond][metric]["mean"]
            deltas[cond][metric] = round(f - c, 3) if f is not None and c is not None else None

    return {
        "per_condition": stats,
        "deltas_vs_full": deltas,
        "inter_pass": {
            "pearson_r_all": round(r_pearson, 3),
            "per_metric_pearson": per_metric_r,
            "n_pairs": len(flat1),
        },
    }


