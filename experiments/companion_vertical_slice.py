def run_cell(condition: str, seed: int, out_dir: Path, *, mode: str,
             llm_client: bool = False) -> dict:
    """Run one (condition, seed) cell through the integrated path.

    mode='structural' -> deterministic fake client + scripted judge +
    restart checkpoints. mode='ablation' -> real LLM client (if llm_client)
    + scripted judge, continuous run.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    db_path = out_dir / f"cell_{condition.lower()}_seed{seed}.db"
    if db_path.exists():
        db_path.unlink()

    apply_condition_patches(condition)

    persona = PersonaParams()
    timing = TimingParams()
    variant = MoodVariant.DECOUPLED_OFFSETS
    profile = build_persona(seed, graph=build_catalog())

    if llm_client:
        client: LLMClient = OpenAICompatibleClient()
    else:
        client = DeterministicClient(seed)  # type: ignore[assignment]
    judge = CyclingScriptedJudge(seed)

    store = SQLiteStore(db_path)
    clock = VirtualClock(0.0)
    session = make_session(condition, seed, store, clock, client, judge,
                           profile, persona, timing, variant)
    sleeper = RecordingSleeper()
    # Initial plan for day 0: the runtime's first replan happens at the
    # day-1 midnight and would otherwise plan day 0 retroactively — every
    # day-0 event would be born overdue and spuriously expire. Planning the
    # first day up front (adj neutral, scores=None) gives the firing loop
    # its day-0 rows from t_h=0 (INSERT OR IGNORE keeps them on replans).
    ProactiveSchedule.plan_and_persist(
        1, seed, persona, timing, store,
        reason=REASON_SCHEDULE, scores=None,
    )

    # telemetry accumulates across restart segments (message ids are unique
    # across the whole DB, so merges are safe)
    all_controls: dict[int, dict] = {}
    all_directives: dict[int, dict] = {}
    all_arcs: dict[int, dict] = {}

    msgs = user_script(seed, mode)
    checkpoint_ends = [d * 24.0 for d in CHECKPOINT_DAYS] if mode == "structural" else []
    segment_ends = sorted(set(checkpoint_ends + [END_H]))
    start_h = 0.0
    i4_violations: list[str] = []
    restart_loss: list[dict] = []

    for seg_end in segment_ends:
        from harness.channels.base import FakeChannel

        runtime = make_runtime(condition, session, store, seed, timing, seg_end,
                               sleeper, FakeChannel())
        asyncio.run(_run_segment(session, runtime, msgs, start_h, seg_end,
                                 store, seed))
        # The runtime exits as soon as the clock reaches seg_end. A pending
        # event due strictly before seg_end that lost the final timer race
        # to the rollover loop's end jump is honestly expired (its validity
        # window elapsed — the runtime's own late-event handling): mark it
        # so I4 never sees an overdue pending row at the checkpoint.
        for r in store.pending_schedule_events(seed):
            if float(r["t_h"]) < seg_end - 1e-6:
                store.mark_schedule_expired(seed, float(r["t_h"]))
        all_controls.update(session.controls_by_message)
        all_directives.update(session.directives_by_message)
        all_arcs.update(session.arc_progress_by_day)
        start_h = seg_end
        if seg_end < END_H:
            i4_violations.extend(_check_i4(store, seg_end, seed))
            fp_pre = _persist_fingerprint(store, seed)
            store.close()
            store = SQLiteStore(db_path)
            clock = VirtualClock(seg_end)
            session = make_session(condition, seed, store, clock, client, judge,
                                   profile, persona, timing, variant)
            fp_post = _persist_fingerprint(store, seed)  # before any continuation writes
            diffs = _fingerprint_diff(fp_pre, fp_post)
            restart_loss.append({"checkpoint_h": seg_end, "diffs": diffs})
            # Resume procedure: roll into the checkpoint day (finalize is
            # judgement-guarded -> no-op), then replicate the midnight replan
            # so the day after a checkpoint keeps its proactive plan (identical
            # rows to a no-restart run: day_scores is stable once judged).
            session.ensure_day(int(seg_end // 24))
            day = session.clock.day()
            scores = day_scores(store, day, timing)
            ProactiveSchedule.plan_and_persist(
                day + 1, seed, persona, timing, store,
                reason=REASON_SCHEDULE, scores=scores,
            )
    i4_violations.extend(_check_i4(store, END_H, seed))

    msgs_all = _all_messages(store)
    n_messages = len(msgs_all)
    n_proactive = sum(1 for m in msgs_all if m["proactive"])
    records = {
        "condition": condition,
        "seed": seed,
        "mode": mode,
        "db": str(db_path),
        "n_messages": n_messages,
        "n_proactive": n_proactive,
        "controls_by_message": {str(k): v for k, v in all_controls.items()},
        "directives_by_message": {str(k): v for k, v in all_directives.items()},
        "arc_progress_by_day": {str(k): v for k, v in all_arcs.items()},
        "sleeper_delays": sleeper.delays,
        "i4_violations": i4_violations,
        "restart_loss": restart_loss,
        "model": "fake" if not llm_client else MODEL,
    }
    (out_dir / f"records_{condition.lower()}_seed{seed}.json").write_text(
        json.dumps(records, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    store.close()
    if llm_client:
        client.close()
    return records


def _all_messages(store: SQLiteStore) -> list[dict]:
    return [dict(r) for r in store.conn.execute(
        "SELECT * FROM messages ORDER BY id").fetchall()]


def _fingerprint_diff(pre: dict, post: dict) -> int:
    total = 0
    for key in pre:
        total += int(pre[key] != post[key])
    return total


