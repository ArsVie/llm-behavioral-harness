def build_trace_cmd(out_dir: Path) -> int:
    demo = out_dir / "ablation" / "cell_full_seed5001.db"
    if not demo.exists():
        print(f"ERROR: demo db missing: {demo}")
        return 1
    store = SQLiteStore(demo)
    rec_path = out_dir / "ablation" / "records_full_seed5001.json"
    records = json.loads(rec_path.read_text(encoding="utf-8")) if rec_path.exists() else {}
    controls = {int(k): v for k, v in records.get("controls_by_message", {}).items()}
    msgs = _all_messages(store)
    fired = [
        i for i in store.list_proactive_intents()
        if _intent_status(store, i.id) == "fired"
    ]
    interests = {i.name for i in store.list_interests()}
    entries = []
    for m in msgs:
        if not m["proactive"]:
            continue
        mt = float(m["t_h"])
        best = min(fired, key=lambda i: abs(i.created_t_h - mt)) if fired else None
        intent = best if best is not None and abs(best.created_t_h - mt) <= 24.0 else None
        src = store.resolve_intent_source(intent) if intent else None
        agenda_id = None
        arc_id = None
        interest = None
        if isinstance(src, AgendaItem):
            agenda_id = src.id
            if src.source_type == "arc":
                arc_id = src.source_id
            elif src.source_type == "interest":
                interest = src.source_id
        elif isinstance(src, LifeArc):
            arc_id = src.id
            interest = src.interest
        elif src is not None and intent is not None and intent.reason == "shared_interest":
            interest = next((t for t in src.tags if t in interests), None)
        entries.append(
            {
                "message_id": int(m["id"]),
                "day": int(m["day"]) + 1,
                "t_h": float(m["t_h"]),
                "local_hour": float(m["t_h"]) % 24.0,
                "intent_id": intent.id if intent else None,
                "reason": intent.reason if intent else None,
                "source_type": intent.source_type if intent else None,
                "source_id": intent.source_id if intent else None,
                "agenda_item": agenda_id,
                "life_arc": arc_id,
                "interest": interest,
                "controls": controls.get(int(m["id"])),
                "hook": intent.hook if intent else None,
                "evidence": intent.evidence if intent else None,
            }
        )
    store.close()
    payload = {
        "demo_run": "FULL seed 5001 (real model, deepseek-v4-flash, 30 days)",
        "schema": "per-spontaneous-message provenance chain (Gate 5 audit)",
        "n_spontaneous": len(entries),
        "entries": entries,
    }
    (out_dir / "trace.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"trace.json: {len(entries)} spontaneous messages")
    return 0


