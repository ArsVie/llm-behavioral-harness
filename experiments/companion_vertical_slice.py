def recall_embedder(text: str, *, dim: int = 1024, seed: int = 0) -> list[float]:
    """Deterministic seeded embedder for the A10 experiment (injected into the
    memory lane; the A5 default 64-dim hash embedder is a test stand-in and is
    too collision-prone for the frozen M3/M4 recall bars).

    Features: word unigrams + character bigrams, signed feature hashing into
    1024 dims (SHA-256 based — stable across processes). The richer feature
    set and larger dim make lexical similarity genuinely discriminative while
    staying fully deterministic.
    """
    import hashlib

    vec = [0.0] * dim
    feats: list[str] = []
    for tok in re.findall(r"[a-z0-9]+", text.lower()):
        feats.append("w:" + tok)
        if len(tok) >= 3:
            for i in range(len(tok) - 1):
                feats.append("b:" + tok[i:i + 2])
    for f in feats:
        d = hashlib.sha256(f"{seed}:{f}".encode("utf-8")).digest()
        idx = int.from_bytes(d[:4], "little") % dim
        sign = 1.0 if d[4] & 1 else -1.0
        vec[idx] += sign
    norm = math.sqrt(sum(v * v for v in vec))
    if norm == 0.0:
        vec[0] = 1.0
        return vec
    return [v / norm for v in vec]

